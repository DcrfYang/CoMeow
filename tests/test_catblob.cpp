int main() {
    printf("-- a real cat image --\n");
    CatBrief b;
    check(catblob_parse(kLittleJohn, sizeof(kLittleJohn), b), "parses");
    check(strcmp(b.name, "Little John") == 0, "name");
    check(b.level == 2, "level");
    check(b.klass == brief_class_from_key("Druid"), "class from the collar");
    check(b.fur == 43 && b.coat == 65, "fur and collar palette rows");
    check(b.hp == 16, "current health");
    check(b.maxhp == 16, "max health floor = 4 x (CON 6 + the Druid's -2)");

    printf("-- refuses what it cannot read --\n");
    CatBrief keep; strcpy_s(keep.name, "keep");
    check(!catblob_parse(kLittleJohn, sizeof(kLittleJohn) - 200, keep), "a truncated image is refused");
    check(strcmp(keep.name, "keep") == 0, "...and leaves the output untouched");
    uint8_t bad[sizeof(kLittleJohn)]; memcpy(bad, kLittleJohn, sizeof(bad)); bad[0] = 18;
    check(!catblob_parse(bad, sizeof(bad), keep), "another layout version is refused");
    check(!catblob_parse(nullptr, 0, keep), "null is refused");

    printf("-- CATS round-trips --\n");
    CatsMsg m; m.count = 2;
    m.cats[0] = b;
    m.cats[1] = b; strcpy_s(m.cats[1].name, "\xE5\xB0\x8F\xE7\x99\xBD"); m.cats[1].hp = kBriefFullHp; m.cats[1].fur = -1;
    uint8_t buf[1024];
    const uint32_t n = enc_cats(buf, sizeof(buf), m);
    check(n > 0, "encodes");
    Reader r(buf, n);
    check(r.u8v() == MSG_CATS, "message type is CATS");
    CatsMsg d;
    check(dec_cats(r, d), "decodes");
    check(d.count == 2 && strcmp(d.cats[0].name, "Little John") == 0 && d.cats[0].level == 2, "cat 0");
    check(strcmp(d.cats[1].name, m.cats[1].name) == 0 && d.cats[1].hp == kBriefFullHp && d.cats[1].fur == -1,
          "cat 1 (UTF-8 name, full health, no fur)");
    m.count = kBriefCats + 1;
    check(enc_cats(buf, sizeof(buf), m) == 0, "more cats than the cap is refused");
    { uint8_t bogus[2] = { MSG_CATS, 200 }; Reader r3(bogus, 2); r3.u8v(); CatsMsg z;
      check(!dec_cats(r3, z), "a count past the cap is refused"); }

    printf("%s\n", g_fail ? "FAILED" : "all passed");
    return g_fail ? 1 : 0;
}
