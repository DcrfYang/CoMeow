// mgmp_indepevt.h -- EXPERIMENTAL (ui.exp_indep_events, the HOST's setting, HELLO rules bit 3, proto 102): the random "?" events are each
// player's own (2026-10-22).
//
// Without it every peer is shown the host's event with the host's cats as the party, the host clicks, and the clients replay the click.
// With it, on a random event node (type 9 event / 10 optional_event):
//   * THE DRAW STAYS THE HOST'S. The event is drawn while the party is still the shared one (the host's cats on every peer), from the
//     same stream and the same used-event list, so every peer draws the same event -- a peer whose own state forces another event
//     (ExtraLife after a death) keeps it, as the user allowed.
//   * THEN EACH PLAYER'S OWN CATS. Right after the draw, inside the event's constructor and before its subject cat is picked, a client
//     puts its own cats into the party (roster_party_swap_for_own_event), so the subject is one of its own.
//   * EACH PLAYER CHOOSES. No choice crosses the wire for such an event: the host does not publish, the client's click stands.
//   * ONLY FOR EVENTS WHOSE EFFECTS STAY ON THE PLAYER'S OWN SAVE AND CATS (mgmp_event_class.h, generated by scratch/gen_event_class.py).
//     Weather, the next fight's spawns / ambushes / global effects, the next events, a fight started by the event, the familiar list,
//     adventure tokens, quests, unlocks, chapters -- an event touching any of these follows the host exactly as before, and so do the
//     story (Quest_*) and special_event nodes.
//   * THE HOST WAITS FOR EVERYBODY. A client's own event changes its own cats, which reach the host by catsync; so the host may not
//     leave an event node (the next node could be a battle built from them) until every client said it is done with its event there,
//     after publishing its cats (ChapterMsg kChapterEventDone). The host's click is refused with a toast meanwhile; after kHoldMaxMs the
//     host goes on regardless (logged), so a lost message cannot lock the run.
//
// Logs: grep INDEPEVT.
#pragma once

#include <cstdint>

namespace mgmp {

// The room plays with the setting and this peer stands on a random event node.
bool indepevt_active();

// h_EvSetup, around the WorldEvent constructor (`this`, and the event name the constructor was given). A main-quest event (a map's Quest_ node, type 11) that
// qualifies (mgmp_event_class.h: event_class_quest_independent) is each player's own while the host's party wears no main-story item; it is decided here, before the
// constructor picks its subject cat (0.1.66).
void indepevt_ctor_begin(void* world_event, const void* name_string);
void indepevt_ctor_end(void* world_event);
// The pool draw returned `out_name` (a std::string*): where the own-event decision is made. `in_ctor`: drawn inside the WorldEvent
// constructor (it was given "random"); otherwise drawn by the event node itself (EnterNode), before the event scene and its constructor --
// the constructor that then gets this name is claimed at its end.
void indepevt_after_pick(void* out_name, bool in_ctor);

// CLIENT: the host's drawn event of an event node (proto 103): low 32 bits of the node seed and the hash of the event name.
void indepevt_on_host_event(uint8_t from, uint32_t seed_lo, uint32_t name_hash);
// true: this peer drew a random event of its own on node `seed` (each player's party is then its own cats).
bool indepevt_own_node(uint64_t seed);
// true: this WorldEvent is this player's own -- no choice is published or replayed.
bool indepevt_is_own(const void* world_event);
// Every frame the event screen updates (mgmp_choice). In an own event it also keeps the next event's difficulty bonus (MewDirector+0x6D0,
// `next_event_bonus`) at what it was when the event came up, on every peer: the next event must be the same everywhere.
void indepevt_on_event_frame(const void* world_event);
// An event result that would make the next draw differ between the players: true = skip it (an own event), logged once per kind.
bool indepevt_suppress(const void* world_event, const char* what);

// Every frame (after session_update): a client tells the host when it is done with its event node.
void indepevt_tick();
// HOST: a client is done with its event at node `seed`.
void indepevt_on_done(uint8_t from, uint64_t seed);
// HOST, h_EnterNode: true = a client is still on its own event here -- the click is refused (a toast says why).
bool indepevt_hold_node();

} // namespace mgmp
